#!/usr/bin/env python3
"""Turn a staff CSV into SQL you can paste into a hosted database's web editor (Neon / Supabase SQL editor).
CSV header: email,name,role      role = viewer | editor | reviewer | admin (blank = viewer; every role is organisation-wide)
Usage:  python3 scripts/staff_to_sql.py staff.csv > staff.sql
Rows with an invalid email or role stop the run with a clear message, so a typo never reaches the database."""
import csv, re, sys
ROLES = {"viewer", "editor", "reviewer", "admin"}; EMAIL = re.compile(r"^[^@\s'\";]+@[^@\s'\";]+\.[^@\s'\";]+$")
q = lambda v: "'" + v.replace("'", "''") + "'"
def main(path):
    out, errs = ["-- generated by scripts/staff_to_sql.py : staff accounts (sign-in is by emailed one-time code)", "BEGIN;"], []
    with open(path, newline="", encoding="utf-8-sig") as f:
        for n, r in enumerate(csv.DictReader(f), start=2):
            e = (r.get("email") or "").strip().lower(); name = (r.get("name") or "").strip() or e.split("@")[0].replace(".", " ").title()
            role = (r.get("role") or "viewer").strip().lower() or "viewer"
            if not EMAIL.match(e): errs.append(f"line {n}: '{e}' is not a valid email"); continue
            if role not in ROLES: errs.append(f"line {n}: role '{role}' must be one of {sorted(ROLES)}"); continue
            out.append(f"INSERT INTO users(email,display_name) VALUES({q(e)},{q(name)}) ON CONFLICT(email) DO UPDATE SET display_name=excluded.display_name, is_active=true;")
            for rr in {role, "viewer"}:
                out.append(f"INSERT INTO user_roles(user_id,dept_id,role) SELECT id,NULL,'{rr}' FROM users WHERE email={q(e)} ON CONFLICT DO NOTHING;")
    if errs: sys.exit("\n".join(errs) + f"\n{len(errs)} problem(s). No SQL produced.")
    out.append("COMMIT;"); print("\n".join(out))
if __name__ == "__main__":
    main(sys.argv[1]) if len(sys.argv) > 1 else sys.exit(__doc__)
